#!/usr/bin/env node
// `npm run test:all:safe` — every LOCAL, SIDE-EFFECT-FREE verification of
// MAASTAC AI in one command. Node only, no dependencies.
//
// Safety guarantees (enforced here, not assumed):
//   * No real services: every child process gets an environment with NO
//     Anthropic key, an unreachable ANTHROPIC_BASE_URL (127.0.0.1:9), NO
//     Supabase credentials, quotas OFF and NO HubSpot credentials. dotenv
//     never overrides a variable that already exists, so server/.env's real
//     values can't leak back in. A test that tried to reach Anthropic or
//     Supabase would fail locally instead of spending money or touching data.
//   * No repository writes: the production build goes to a fresh temporary
//     directory (never dist/), deleted at the end, even on failure.
//   * No installs, no git operations, no deploys.
//   * SQL tests are NOT run (they need Docker, whose state this script can't
//     control). See `--sql-info` and REPORTE_TEST_ALL_SAFE.txt.
//
// Exit code: 0 if every step passed, 1 otherwise. All steps run even if an
// earlier one fails, so the summary is always complete.

import { spawnSync } from 'node:child_process'
import { mkdtempSync, readdirSync, rmSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const serverDir = path.join(root, 'server')
const isWindows = process.platform === 'win32'

if (process.argv.includes('--sql-info')) {
  console.log(
    [
      'SQL tests are not part of test:all:safe (they need Docker).',
      'Run them manually against a DISPOSABLE Postgres only — never Supabase staging/production:',
      '  supabase/schema.sql, then supabase/tests-usage-quotas.sql and supabase/tests-org-bootstrap.sql',
      'See REPORTE_TEST_ALL_SAFE.txt for the exact procedure.',
    ].join('\n'),
  )
  process.exit(0)
}

// ── Safe environment for every child process ────────────────────────────────
const SAFE_OVERRIDES = {
  ANTHROPIC_API_KEY: '',
  ANTHROPIC_BASE_URL: 'http://127.0.0.1:9',
  SUPABASE_URL: '',
  SUPABASE_SERVICE_ROLE_KEY: '',
  CHAT_QUOTAS_ENABLED: 'false',
  HUBSPOT_CLIENT_ID: '',
  HUBSPOT_CLIENT_SECRET: '',
  HUBSPOT_REDIRECT_URI: '',
  HUBSPOT_TOKEN_ENCRYPTION_KEY: '',
  FRONTEND_URL: '',
  CI: 'true',
}
const safeEnv = { ...process.env, ...SAFE_OVERRIDES }

function bin(dir, name) {
  return path.join(dir, 'node_modules', '.bin', isWindows ? `${name}.cmd` : name)
}

function quote(arg) {
  return /[\s"]/.test(arg) ? `"${arg.replace(/"/g, '\\"')}"` : arg
}

function run(label, command, args, cwd) {
  const started = Date.now()
  console.log(`\n▶ ${label}\n  $ ${[command, ...args].map(quote).join(' ')}`)
  // shell: true is required on Windows to run the .cmd shims; every argument
  // here is generated by this script (paths and fixed flags), never user input.
  const result = spawnSync([command, ...args].map(quote).join(' '), {
    cwd,
    env: safeEnv,
    stdio: 'inherit',
    shell: true,
  })
  const seconds = ((Date.now() - started) / 1000).toFixed(1)
  const ok = result.status === 0
  console.log(`${ok ? '✔' : '✖'} ${label} (${seconds}s, exit ${result.status ?? result.signal})`)
  return { label, ok, seconds }
}

const frontendUnitTests = readdirSync(path.join(root, 'tests'))
  .filter((name) => name.endsWith('.test.ts'))
  .sort()
  .map((name) => path.join('tests', name))

const buildDir = mkdtempSync(path.join(os.tmpdir(), 'maastac-safe-build-'))
const results = []

try {
  results.push(run('Frontend · TypeScript (tsc -b)', bin(root, 'tsc'), ['-b'], root))
  results.push(run('Frontend · Lint (oxlint)', bin(root, 'oxlint'), [], root))
  results.push(
    run(`Frontend · Pruebas unitarias (${frontendUnitTests.length} archivos, node:test)`, bin(serverDir, 'tsx'), ['--test', ...frontendUnitTests], root),
  )

  const build = run('Frontend · Build de producción (carpeta temporal)', bin(root, 'vite'), ['build', '--outDir', buildDir, '--emptyOutDir', '--logLevel', 'warn'], root)
  results.push(build)
  if (build.ok) {
    results.push(run('Frontend · Bundle sin detalles internos', process.execPath, [path.join('scripts', 'check-production-bundle.mjs'), buildDir], root))
  } else {
    results.push({ label: 'Frontend · Bundle sin detalles internos', ok: false, seconds: '0.0', skipped: 'no build' })
  }

  results.push(run('Backend · TypeScript (tsc --noEmit)', bin(serverDir, 'tsc'), ['-p', 'tsconfig.json', '--noEmit'], serverDir))
  results.push(run('Backend · Pruebas (vitest)', bin(serverDir, 'vitest'), ['run', '--maxWorkers=2', '--testTimeout=60000'], serverDir))
} finally {
  rmSync(buildDir, { recursive: true, force: true })
}

// ── Summary ─────────────────────────────────────────────────────────────────
console.log('\n══════════ test:all:safe — resumen ══════════')
for (const r of results) {
  console.log(`${r.ok ? '✔' : '✖'} ${r.label}${r.skipped ? ` (omitido: ${r.skipped})` : ''} — ${r.seconds}s`)
}
console.log('ℹ SQL (Docker) no incluido: ver `node scripts/test-all-safe.mjs --sql-info`.')
const failed = results.filter((r) => !r.ok)
console.log(failed.length === 0 ? '\nRESULTADO: TODO OK' : `\nRESULTADO: ${failed.length} paso(s) fallaron`)
process.exit(failed.length === 0 ? 0 : 1)
